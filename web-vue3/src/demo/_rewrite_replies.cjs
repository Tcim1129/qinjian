// Helper: 替换指定 key 之间的 content 值
function replaceContentValue(src, searchSnippet, oldValue, newValue) {
  const idx = src.indexOf(searchSnippet);
  if (idx === -1) {
    console.error(`❌ 搜索片段未找到: "${searchSnippet}"`);
    return src;
  }
  if (!src.includes(oldValue)) {
    console.error(`❌ 旧值未找到: "${oldValue.substring(0, 60)}..."`);
    return src;
  }
  const result = src.replace(oldValue, newValue);
  if (result === src) {
    console.error(`❌ 替换未生效: "${oldValue.substring(0, 60)}..."`);
  }
  return result;
}

